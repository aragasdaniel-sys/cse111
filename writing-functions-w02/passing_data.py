def add(x, y):
    """
    Adds two numbers together and returns the result
    """
    result = x + y
    return result

number1 = 3
number2 = 4

first_total = add(number1, number2)
print("Calling the function once:")
print(first_total)

number3 = 27
number4 = 1476

second_total = add(number3, number4)
print()
print("Calling the function twice: ")
print(second_total)

